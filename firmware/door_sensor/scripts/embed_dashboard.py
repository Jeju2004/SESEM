"""Pack the caregiver dashboard page into the hub firmware.

Runs before every build of the `esp32hub` environments (platformio.ini,
extra_scripts) and can also be run by hand:  python scripts/embed_dashboard.py

Reads the SAME page the laptop server uses - dashboard/static/v2/index.html,
home.css and home.js - so the hub never drifts from it, then:
  * inlines the CSS and JS, so a phone fetches one file (the hub serves one
    client request at a time per socket; fewer requests = faster first load);
  * applies the few hub-only changes below, each checked to have applied, so a
    later edit of the page that moves the text fails the build loudly instead
    of shipping an unpatched page;
  * gzips it and writes include/hub_page.h (a byte array in flash).

The header is rewritten only when its content changes, so an unchanged page
does not force a recompile.
"""

from __future__ import annotations

import gzip
import os
import sys

try:
    Import("env")  # type: ignore[name-defined]  # noqa: F821 - PlatformIO/SCons
    PROJECT_DIR = env["PROJECT_DIR"]  # type: ignore[name-defined]  # noqa: F821
except NameError:
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PAGE_DIR = os.path.normpath(os.path.join(PROJECT_DIR, "..", "..", "dashboard", "static", "v2"))
OUT = os.path.join(PROJECT_DIR, "include", "hub_page.h")

# (file, what to find, what to put instead, why). Applied before inlining.
PATCHES = [
    ("index.html", '<a href="/classic">Classic view</a>',
     "Served by the SESEMSG hub - no laptop, no internet.",
     "the hub has no classic page"),
    # The hub has no real-time clock and no internet. Every phone that opens the
    # page tells it the time once; the hub stores all times relative to its own
    # uptime, so events recorded before that still get the right clock times.
    ("home.js", "fetch(API + '/auth/status', { cache: 'no-store' })",
     "fetch(API + '/auth/status?now=' + Date.now(), { cache: 'no-store' })",
     "give the hub the phone's clock"),
]
CSS_LINK = '<link rel="stylesheet" href="/static/v2/home.css">'
JS_TAG = '<script src="/static/v2/home.js"></script>'


def read(name: str) -> str:
    with open(os.path.join(PAGE_DIR, name), "r", encoding="utf-8") as fh:
        return fh.read()


def replace_once(text: str, find: str, repl: str, why: str) -> str:
    n = text.count(find)
    if n != 1:
        sys.exit(f"embed_dashboard: expected exactly one '{find}' ({why}), found {n}. "
                 "The dashboard page changed - update PATCHES in this script.")
    return text.replace(find, repl)


def build() -> bytes:
    files = {name: read(name) for name in ("index.html", "home.css", "home.js")}
    for name, find, repl, why in PATCHES:
        files[name] = replace_once(files[name], find, repl, why)
    if "</script" in files["home.js"].lower():
        sys.exit("embed_dashboard: home.js contains '</script' - cannot inline it safely")
    html = replace_once(files["index.html"], CSS_LINK, "<style>" + files["home.css"] + "</style>",
                        "inline the stylesheet")
    html = replace_once(html, JS_TAG, "<script>" + files["home.js"] + "</script>",
                        "inline the script")
    return gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)


def write_header(gz: bytes) -> bool:
    lines = [
        "// GENERATED by scripts/embed_dashboard.py from dashboard/static/v2 - do not edit.",
        "// The hub serves this as GET / with Content-Encoding: gzip.",
        "#pragma once",
        "#include <Arduino.h>",
        f"static const size_t HUB_PAGE_GZ_LEN = {len(gz)};",
        "static const uint8_t HUB_PAGE_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    if os.path.exists(OUT):
        with open(OUT, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                return False
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return True


gz = build()
changed = write_header(gz)
print(f"embed_dashboard: {PAGE_DIR} -> include/hub_page.h, {len(gz)} bytes gzipped"
      f"{' (updated)' if changed else ' (unchanged)'}")
